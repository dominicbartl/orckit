import { For, Show, createSignal, type JSX } from 'solid-js';
import { Card } from '../components/Card';
import { MultiSelect } from '../components/MultiSelect';
import { ParsedEntryRow } from '../components/ParsedEntryRow';
import { ParsedLogView } from '../components/ParsedLogView';
import { ValueTree } from '../components/ValueTree';
import type { IdeLink, LogValue, ParsedLogEntry, ParsedLogState, UserLogEntry } from '../lib/types';
import fixture from './sink-parsed-fixture.json';

/**
 * Kitchen-sink sections for the parsed log view. The entries are real: the
 * server's assembler run over tests/fixtures/firebase-logging (scrubbed
 * recordings of a NestJS-on-Cloud-Functions app), regenerated by hand when
 * the entry shape changes.
 */
const ENTRIES = fixture as ParsedLogEntry[];

const SAMPLE_IDE: IdeLink = { command: 'webstorm', root: '/home/dev/workspace/app' };
const CWD = '/home/dev/workspace/app/backend';

const s = (value: string): LogValue => ({ kind: 'string', value });
const n = (text: string): LogValue => ({ kind: 'number', text });

/** One of every node kind the server's parser produces. */
const ALL_KINDS: LogValue = {
  kind: 'object',
  ref: 1,
  props: [
    { key: 'name', value: s('linden') },
    { key: 'covers', value: n('42') },
    { key: 'ratio', value: n('NaN') },
    { key: 'big', value: n('10n') },
    { key: 'active', value: { kind: 'boolean', value: true } },
    { key: 'closedAt', value: { kind: 'null' } },
    { key: 'note', value: { kind: 'undefined' } },
    { key: 'createdAt', value: { kind: 'date', text: '2026-11-23T13:02:11.204Z' } },
    {
      key: 'pathParams',
      value: {
        kind: 'object',
        tag: '[Object: null prototype]',
        props: [{ key: 'restaurantId', value: s('harborhall') }],
      },
    },
    { key: 'handler', value: { kind: 'special', text: '[Function: getBootstrapData]' } },
    { key: 'self', value: { kind: 'special', text: '[Circular *1]' } },
    {
      key: 'deep',
      value: {
        kind: 'object',
        props: [
          {
            key: 'a',
            value: {
              kind: 'object',
              props: [{ key: 'b', value: { kind: 'special', text: '[Object]' } }],
            },
          },
        ],
      },
    },
    {
      key: 'tables',
      value: { kind: 'array', items: [n('1'), n('2'), n('3')], more: 97 },
    },
    {
      key: 'byArea',
      value: {
        kind: 'map',
        tag: 'Map(2)',
        pairs: [
          { key: s('terrace'), value: n('12') },
          { key: s('bar'), value: n('6') },
        ],
      },
    },
    { key: 'tags', value: { kind: 'array', tag: 'Set(2)', items: [s('vip'), s('late')] } },
    { key: 'content-type', value: s('application/json') },
    { key: 'empty', value: { kind: 'object', props: [] } },
  ],
};

const STRIPE = ENTRIES.find(
  (e): e is UserLogEntry => e.kind === 'log' && e.level === 'error' && e.value !== undefined,
);
const REQUEST = ENTRIES.find(
  (e): e is UserLogEntry => e.kind === 'log' && e.handler !== undefined && e.value !== undefined,
);
const ROWS: ParsedLogEntry[] = [
  ENTRIES.find((e) => e.kind === 'system')!,
  ENTRIES.find((e) => e.kind === 'execution')!,
  ENTRIES.find((e) => e.kind === 'log' && e.context !== undefined)!,
  REQUEST!,
  STRIPE!,
  ENTRIES.find((e) => e.kind === 'log' && e.message === 'Order placed')!,
];

const STATES: { title: string; state: ParsedLogState; entries: ParsedLogEntry[] }[] = [
  {
    title: 'waiting — the emulators are still booting',
    state: {
      source: 'firebase',
      state: 'waiting',
      detail: 'waiting for the emulator hub at 127.0.0.1:4400',
    },
    entries: [],
  },
  {
    title: 'unavailable — no logging emulator',
    state: {
      source: 'firebase',
      state: 'unavailable',
      detail:
        'the logging emulator is not running — enable the Emulator UI (emulators.ui in firebase.json) or set START_LOGGING_EMULATOR=true in the process env',
    },
    entries: [],
  },
  {
    title: 'idle — process not running',
    state: { source: 'firebase', state: 'idle' },
    entries: [],
  },
  {
    title: 'connected — no logs yet',
    state: { source: 'firebase', state: 'connected', url: 'ws://127.0.0.1:4500' },
    entries: [],
  },
];

/** `count` entries cycled from the fixture, ids and times renumbered. */
function stressEntries(count: number): ParsedLogEntry[] {
  const start = Date.UTC(2026, 10, 23, 9, 0, 0);
  return Array.from({ length: count }, (_, i) => ({
    ...ENTRIES[i % ENTRIES.length]!,
    id: i,
    ts: start + i * 137,
  }));
}

export function ParsedLogSinkSections(props: {
  Section: (p: { title: string; subtitle?: string; children: JSX.Element }) => JSX.Element;
}) {
  const Section = props.Section;
  const [expanded, setExpanded] = createSignal<ReadonlySet<number>>(new Set([REQUEST?.id ?? -1]));
  const [facet, setFacet] = createSignal<Set<string> | null>(null);
  const [stress, setStress] = createSignal<ParsedLogEntry[] | null>(null);
  const [renderMs, setRenderMs] = createSignal<number | null>(null);

  const mountStress = () => {
    const entries = stressEntries(5000);
    const t0 = performance.now();
    setStress(entries);
    // Two frames: one to commit the DOM, one after layout.
    requestAnimationFrame(() =>
      requestAnimationFrame(() => setRenderMs(Math.round(performance.now() - t0))),
    );
  };

  return (
    <>
      <Section
        title="Value tree"
        subtitle="A parsed console.log object or structured log's fields. Every annotation util.inspect printed stays visible: class and null-prototype tags, <ref *1> / [Circular *1], [Object] depth truncation, … N more items. Containers past depth 2 start collapsed."
      >
        <div class="grid gap-3 lg:grid-cols-2">
          <Card>
            <ValueTree value={ALL_KINDS} />
          </Card>
          <Show when={STRIPE?.value}>
            {(v) => (
              <Card>
                <div class="mb-2 text-[11px] font-mono text-fg-tertiary">
                  A 79-line Stripe error dump, re-merged and parsed
                </div>
                <ValueTree value={v()} expandDepth={1} />
              </Card>
            )}
          </Show>
        </div>
      </Section>

      <Section
        title="Parsed log entries"
        subtitle="One row per kind: emulator system line, function execution (ƒ + duration), Nest logger warning with its context, a request log (handler, method / status / latency / route chips, preview), an error with its stack split off, a structured logger line. Click a row with ▸ to expand."
      >
        <div class="rounded-md border border-border-subtle bg-surface-inset py-1.5 font-mono text-[12px] leading-[1.5]">
          <For each={ROWS}>
            {(entry) => (
              <ParsedEntryRow
                entry={entry}
                expanded={expanded().has(entry.id)}
                onToggle={() =>
                  setExpanded((prev) => {
                    const next = new Set(prev);
                    if (next.has(entry.id)) next.delete(entry.id);
                    else next.add(entry.id);
                    return next;
                  })
                }
                ide={SAMPLE_IDE}
                baseDir={CWD}
              />
            )}
          </For>
        </div>
      </Section>

      <Section
        title="Multi-select"
        subtitle="Facet filter: counts per value, an 'only' shortcut on hover, all / none. Highlighted once it narrows anything."
      >
        <div class="flex items-center gap-3 h-10">
          <MultiSelect
            label="Function"
            options={[
              { value: 'europe-west1-api', label: 'api', count: 24, title: 'europe-west1-api' },
              {
                value: 'europe-west1-orders',
                label: 'orders',
                count: 4,
                title: 'europe-west1-orders',
              },
              { value: 'europe-west1-core_v2-migrateHttp', label: 'core_v2-migrateHttp', count: 1 },
            ]}
            selected={facet()}
            onChange={setFacet}
          />
          <span class="text-xs font-mono text-fg-tertiary">
            selected: {facet() === null ? 'all' : JSON.stringify([...facet()!])}
          </span>
        </div>
      </Section>

      <Section
        title="Parsed log view"
        subtitle="The Parsed tab for a process with parsed_logs: facets, status-class chips, search, live source pill. Filters persist per process in localStorage."
      >
        <div class="h-[28rem]">
          <ParsedLogView
            name="emulators"
            state={{ source: 'firebase', state: 'connected', url: 'ws://127.0.0.1:4500' }}
            entries={() => ENTRIES}
            generation={1}
            storageKey="orckit:sink:parsed-filters"
            ide={SAMPLE_IDE}
            baseDir={CWD}
          />
        </div>
      </Section>

      <Section
        title="Parsed log view — source states"
        subtitle="Before any entry arrives: waiting for the emulators, no logging emulator (with the fix), process not running, connected but quiet."
      >
        <div class="grid gap-3 lg:grid-cols-2">
          <For each={STATES}>
            {(variant) => (
              <div>
                <div class="mb-1.5 text-[11px] font-mono text-fg-tertiary">{variant.title}</div>
                <div class="h-56">
                  <ParsedLogView
                    name="emulators"
                    state={variant.state}
                    entries={() => variant.entries}
                  />
                </div>
              </div>
            )}
          </For>
        </div>
      </Section>

      <Section
        title="Parsed log view — 5,000 entries"
        subtitle="The default buffer size, rendered without windowing. Mount it to check the first paint stays acceptable; filters and search run over all of it."
      >
        <Show
          when={stress()}
          fallback={
            <button
              type="button"
              class="h-8 px-3 rounded-md border border-border-default bg-surface-2 text-[13px] text-fg-primary hover:bg-surface-3"
              onClick={mountStress}
            >
              Render 5,000 entries
            </button>
          }
        >
          {(entries) => (
            <>
              <div
                class="mb-1.5 text-[11px] font-mono text-fg-tertiary"
                data-testid="stress-render-ms"
              >
                first render: {renderMs() ?? '…'} ms
              </div>
              <div class="h-[28rem]">
                <ParsedLogView
                  name="emulators"
                  state={{ source: 'firebase', state: 'connected', url: 'ws://127.0.0.1:4500' }}
                  entries={entries}
                  generation={2}
                />
              </div>
            </>
          )}
        </Show>
      </Section>
    </>
  );
}
